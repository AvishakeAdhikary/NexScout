"""Object storage abstraction. The filesystem backend is used for dev and desktop deployments.

Keys are generated by the application (never derived from user-supplied filenames), are scoped
per owner, and are validated against a strict pattern before touching the filesystem, so path
traversal isn't possible.
"""

from __future__ import annotations

import hashlib
import os
import re
import tempfile
import uuid
from pathlib import Path
from typing import Protocol

_KEY = re.compile(r"^[0-9a-f-]{36}/[0-9a-f]{2}/[0-9a-f]{64}$")


class ObjectStore(Protocol):
    def put(self, owner_id: uuid.UUID, data: bytes) -> tuple[str, str]:
        """Store bytes; returns (key, sha256 hex)."""
        ...

    def get(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None: ...

    def exists(self, key: str) -> bool: ...


def make_key(owner_id: uuid.UUID, sha256: str) -> str:
    return f"{owner_id}/{sha256[:2]}/{sha256}"


class LocalObjectStore:
    """Content-addressed files under `root/<owner>/<aa>/<sha256>`, written atomically."""

    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        if not _KEY.match(key):
            raise ValueError("Invalid storage key")
        path = (self.root / key).resolve()
        if self.root not in path.parents:
            raise ValueError("Invalid storage key")
        return path

    def put(self, owner_id: uuid.UUID, data: bytes) -> tuple[str, str]:
        digest = hashlib.sha256(data).hexdigest()
        key = make_key(owner_id, digest)
        path = self._path(key)
        if path.exists():
            return key, digest
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
        try:
            with os.fdopen(fd, "wb") as fh:
                fh.write(data)
                fh.flush()
                os.fsync(fh.fileno())
            os.replace(tmp, path)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise
        return key, digest

    def get(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def exists(self, key: str) -> bool:
        return self._path(key).exists()
